-- Day 9: Snowflake Security, Dynamic Masking & RBAC

USE ROLE ACCOUNTADMIN;
USE DATABASE EHDIP_PROD;
USE SCHEMA SECURITY;

-- 1. Create RBAC Roles
CREATE OR REPLACE ROLE EHDIP_DATA_SCIENTIST;
CREATE OR REPLACE ROLE EHDIP_COMPLIANCE_OFFICER;

-- 2. Create Dynamic Masking Policies for PHI
-- Masking for SSN
CREATE OR REPLACE MASKING POLICY mask_ssn AS (val string) RETURNS string ->
  CASE
    WHEN CURRENT_ROLE() IN ('EHDIP_COMPLIANCE_OFFICER', 'ACCOUNTADMIN') THEN val
    ELSE '***-**-****'
  END;

-- Masking for MRN
CREATE OR REPLACE MASKING POLICY mask_mrn AS (val string) RETURNS string ->
  CASE
    WHEN CURRENT_ROLE() IN ('EHDIP_COMPLIANCE_OFFICER', 'ACCOUNTADMIN') THEN val
    ELSE '***-MASKED-MRN-***'
  END;

-- Masking for DOB (Year only for Safe Harbor)
CREATE OR REPLACE MASKING POLICY mask_dob AS (val date) RETURNS date ->
  CASE
    WHEN CURRENT_ROLE() IN ('EHDIP_COMPLIANCE_OFFICER', 'ACCOUNTADMIN') THEN val
    ELSE DATE_TRUNC('YEAR', val)
  END;

