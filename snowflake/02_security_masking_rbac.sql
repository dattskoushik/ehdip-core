-- 4. Grant Access
GRANT USAGE ON DATABASE EHDIP_PROD TO ROLE EHDIP_DATA_SCIENTIST;
GRANT USAGE ON SCHEMA EHDIP_PROD.GOLD TO ROLE EHDIP_DATA_SCIENTIST;
GRANT SELECT ON ALL TABLES IN SCHEMA EHDIP_PROD.GOLD TO ROLE EHDIP_DATA_SCIENTIST;

GRANT USAGE ON DATABASE EHDIP_PROD TO ROLE EHDIP_COMPLIANCE_OFFICER;
